using System;
using System.Linq;
using UnityEngine;
using HarmonyLib;
using UnityEngine.UI;

namespace ShinobiBox
{
    [HarmonyPatch(typeof(StatsIconContainer), "Awake")]
    public static class StatsIconPatches
    {
        [HarmonyPostfix]
        static void Postfix(StatsIconContainer __instance)
        {
            if (__instance == null || __instance._stats_icons == null || __instance._stats_icons.Count == 0) return;

            CreateIcon(__instance, "i_Chakra", "ui/icons/staticon", "Chakra", "Energy used for Shinobi techniques.");
            CreateIcon(__instance, "i_tailed_beast_chakra", "ui/icons/Seal", "Tailed-Beast Chakra", "Reserve generated by a tailed-beast jinchuriki.");
            CreateIcon(__instance, "i_sage_chakra", "ui/icons/staticon", "Sage Chakra", "Nature energy reserve used by sages and senjutsu users.");
            CreateIcon(__instance, "i_blindness", "ui/icons/Blind", "Blindness", "Mangekyo Sharingan usage level. At 25, permanent blindness occurs.");
        }

        public static void CreateIcon(StatsIconContainer container, string id, string spritePath, string title, string desc)
        {
            if (container._stats_icons.ContainsKey(id)) return;

            var template = container._stats_icons.Values.First();
            GameObject cloneGO = UnityEngine.Object.Instantiate(template.gameObject, template.transform.parent);
            cloneGO.name = id;

            StatsIcon icon = cloneGO.GetComponent<StatsIcon>();
            Sprite sprite = SpriteTextureLoader.getSprite(spritePath);
            if (sprite != null) icon.getIcon().sprite = sprite;

            TipButton tip = cloneGO.GetComponent<TipButton>();
            tip.textOnClick = title;
            tip.textOnClickDescription = desc;

            container._stats_icons.Add(id, icon);
        }
    }

    [HarmonyPatch(typeof(UnitStatsElement), "showContent")]
    public static class ChakraValuePatch
    {
        [HarmonyPostfix]
        static void Postfix(UnitStatsElement __instance)
        {
            if (__instance == null || __instance.actor == null || !__instance.actor.isAlive()) return;

            float current = ChakraSystem.GetCurrent(__instance.actor);
            float max = ChakraSystem.GetMax(__instance.actor);

            __instance.setIconValue("i_Chakra", (int)current, (int)max, "", false, "", '/');

            float tailedBeastCurrent = ChakraSystem.GetTailedBeastChakra(__instance.actor);
            float tailedBeastMax = ChakraSystem.GetMaxTailedBeastChakra(__instance.actor);
            __instance.setIconValue("i_tailed_beast_chakra", (int)tailedBeastCurrent, (int)tailedBeastMax, "", false, "", '/');

            float sageCurrent = ChakraSystem.GetSageChakra(__instance.actor);
            float sageMax = ChakraSystem.GetMaxSageChakra(__instance.actor);
            __instance.setIconValue("i_sage_chakra", (int)sageCurrent, (int)sageMax, "", false, "", '/');

            int blindness = 0;
            __instance.actor.data.get("ms_usage", out blindness);
            blindness = Mathf.Min(blindness, 25);
            __instance.setIconValue("i_blindness", blindness, 25, "", false, "", '/');
        }
    }

    // Left exactly as requested - will continue redrawing on Update
    [HarmonyPatch(typeof(UnitWindow), "Update")]
    public static class RealTimeChakraUpdate
    {
        [HarmonyPostfix]
        public static void Postfix(UnitWindow __instance)
        {
            if (!__instance.gameObject.activeSelf || __instance.actor == null || !__instance.actor.isAlive()) return;

            UnitStatsElement stats = __instance.GetComponentInChildren<UnitStatsElement>();
            if (stats != null)
            {
                float current = ChakraSystem.GetCurrent(__instance.actor);
                float max = ChakraSystem.GetMax(__instance.actor);

                stats.setIconValue("i_Chakra", (int)current, (int)max, "", false, "", '/');

                float tailedBeastCurrent = ChakraSystem.GetTailedBeastChakra(__instance.actor);
                float tailedBeastMax = ChakraSystem.GetMaxTailedBeastChakra(__instance.actor);
                stats.setIconValue("i_tailed_beast_chakra", (int)tailedBeastCurrent, (int)tailedBeastMax, "", false, "", '/');

                float sageCurrent = ChakraSystem.GetSageChakra(__instance.actor);
                float sageMax = ChakraSystem.GetMaxSageChakra(__instance.actor);
                stats.setIconValue("i_sage_chakra", (int)sageCurrent, (int)sageMax, "", false, "", '/');

                int blindness = 0;
                __instance.actor.data.get("ms_usage", out blindness);
                blindness = Mathf.Min(blindness, 25);
                stats.setIconValue("i_blindness", blindness, 25, "", false, "", '/');
            }
        }
    }
}