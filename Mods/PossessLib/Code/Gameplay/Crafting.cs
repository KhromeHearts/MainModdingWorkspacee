using System;
using System.Collections.Generic;
using PossessLib.Api;
using PossessLib.Core;
using PossessLib.Model;
using PossessLib.Sync;
using UnityEngine;

namespace PossessLib.Gameplay
{
    /// <summary>
    /// Data-driven crafting. Recipes come from three places, later ones replacing earlier ones with the
    /// same id: auto-recipes derived from the game's own item costs, Data/recipes.json, and the API.
    /// </summary>
    internal static class Crafting
    {
        private static readonly Dictionary<string, RecipeDefinition> _apiRecipes = new Dictionary<string, RecipeDefinition>();
        private static readonly Dictionary<string, RecipeDefinition> _all = new Dictionary<string, RecipeDefinition>();
        private static readonly List<RecipeDefinition> _sorted = new List<RecipeDefinition>();
        private static readonly Dictionary<RecipeDefinition, EquipmentAsset> _autoAssets = new Dictionary<RecipeDefinition, EquipmentAsset>();
        private static bool _built;

        /// <summary>Bumped when the recipe list changes.</summary>
        public static int Version { get; private set; }

        public static void Register(RecipeDefinition pRecipe)
        {
            if (pRecipe == null || string.IsNullOrEmpty(pRecipe.Id) || string.IsNullOrEmpty(pRecipe.ResultId))
            {
                PLLog.Warn("RegisterRecipe: recipe, Id or ResultId is null");
                return;
            }
            _apiRecipes[pRecipe.Id] = pRecipe;
            _built = false;
        }

        public static IReadOnlyList<RecipeDefinition> All
        {
            get
            {
                EnsureBuilt();
                return _sorted;
            }
        }

        private static void EnsureBuilt()
        {
            if (_built) return;
            _built = true;
            _all.Clear();
            _autoAssets.Clear();
            RecipeFile file = DataTables.Recipes;

            if (file.AutoFromGameItems && AssetManager.items != null)
            {
                foreach (EquipmentAsset asset in AssetManager.items.list)
                {
                    RecipeDefinition auto = BuildAutoRecipe(asset, file);
                    if (auto == null) continue;
                    _all[auto.Id] = auto;
                    _autoAssets[auto] = asset;
                }
            }
            if (file.Recipes != null)
            {
                foreach (RecipeEntry entry in file.Recipes)
                {
                    RecipeDefinition def = FromEntry(entry);
                    if (def != null) _all[def.Id] = def;
                }
            }
            foreach (KeyValuePair<string, RecipeDefinition> pair in _apiRecipes) _all[pair.Key] = pair.Value;
            if (file.Disabled != null) foreach (string id in file.Disabled) _all.Remove(id);

            _sorted.Clear();
            _sorted.AddRange(_all.Values);
            _sorted.Sort(CompareRecipes);
            Version++;
            PLLog.Debug("Crafting: " + _sorted.Count + " recipes");
        }

        private static RecipeDefinition BuildAutoRecipe(EquipmentAsset pAsset, RecipeFile pFile)
        {
            if (pAsset == null || string.IsNullOrEmpty(pAsset.group_id)) return null;
            if (pFile.AutoGroups == null || !pFile.AutoGroups.Contains(pAsset.group_id)) return null;
            RecipeDefinition recipe = new RecipeDefinition
            {
                Id = "auto:" + pAsset.id,
                ResultKind = RecipeResultKind.Item,
                ResultId = pAsset.id,
                ResultCount = 1,
                Category = pAsset.equipment_type == EquipmentType.Weapon ? "weapon"
                    : pAsset.equipment_type == EquipmentType.Ring || pAsset.equipment_type == EquipmentType.Amulet ? "accessory" : "armor",
                NearBuildings = pFile.AutoNearBuildings,
                AutoGenerated = true
            };
            float mult = Mathf.Max(0f, pFile.AutoCostMultiplier);
            AddCost(recipe, pAsset.cost_resource_id_1, pAsset.cost_resource_1, mult);
            AddCost(recipe, pAsset.cost_resource_id_2, pAsset.cost_resource_2, mult);
            if (pFile.AutoChargeMoney) recipe.Money = Mathf.CeilToInt(pAsset.get_total_cost * mult);
            if (recipe.Resources.Count == 0 && recipe.Money == 0) return null; // the game gives these away for free
            return recipe;
        }

        private static void AddCost(RecipeDefinition pRecipe, string pResourceId, int pAmount, float pMult)
        {
            if (string.IsNullOrEmpty(pResourceId) || pResourceId == "none" || pAmount <= 0) return;
            if (AssetManager.resources.get(pResourceId) == null) return;
            int amount = Mathf.Max(1, Mathf.CeilToInt(pAmount * pMult));
            pRecipe.Resources.TryGetValue(pResourceId, out int existing);
            pRecipe.Resources[pResourceId] = existing + amount;
        }

        private static RecipeDefinition FromEntry(RecipeEntry pEntry)
        {
            if (pEntry == null || string.IsNullOrEmpty(pEntry.Id)) return null;
            RecipeDefinition def = new RecipeDefinition
            {
                Id = pEntry.Id,
                ResultCount = Mathf.Max(1, pEntry.Count),
                Resources = pEntry.Resources ?? new Dictionary<string, int>(),
                CustomItems = pEntry.CustomItems ?? new Dictionary<string, int>(),
                Money = Mathf.Max(0, pEntry.Money),
                NearBuildings = pEntry.NearBuildings,
                StationRadius = pEntry.StationRadius,
                Category = pEntry.Category ?? "misc"
            };
            if (!string.IsNullOrEmpty(pEntry.ResultItem))
            {
                def.ResultKind = RecipeResultKind.Item;
                def.ResultId = pEntry.ResultItem;
            }
            else if (!string.IsNullOrEmpty(pEntry.ResultResource))
            {
                def.ResultKind = RecipeResultKind.Resource;
                def.ResultId = pEntry.ResultResource;
            }
            else if (!string.IsNullOrEmpty(pEntry.ResultCustom))
            {
                def.ResultKind = RecipeResultKind.Custom;
                def.ResultId = pEntry.ResultCustom;
            }
            else
            {
                PLLog.Warn("Recipe " + pEntry.Id + " has no result_item/result_resource/result_custom");
                return null;
            }
            return def;
        }

        private static int CompareRecipes(RecipeDefinition pA, RecipeDefinition pB)
        {
            int cat = string.CompareOrdinal(pA.Category, pB.Category);
            if (cat != 0) return cat;
            int costA = TotalCost(pA), costB = TotalCost(pB);
            if (costA != costB) return costA.CompareTo(costB);
            return string.CompareOrdinal(pA.Id, pB.Id);
        }

        private static int TotalCost(RecipeDefinition pRecipe)
        {
            int total = pRecipe.Money;
            foreach (KeyValuePair<string, int> pair in pRecipe.Resources) total += pair.Value * 3;
            return total;
        }

        // ------------------------------------------------------------------ queries

        /// <summary>False for results that do not exist (removed asset) or are still locked for the player.</summary>
        public static bool IsVisible(RecipeDefinition pRecipe)
        {
            switch (pRecipe.ResultKind)
            {
                case RecipeResultKind.Item:
                    EquipmentAsset asset = AssetManager.items.get(pRecipe.ResultId);
                    if (asset == null) return false;
                    if (pRecipe.AutoGenerated && DataTables.Recipes.AutoRequireUnlocked && !asset.isAvailable()) return false;
                    return true;
                case RecipeResultKind.Resource:
                    return AssetManager.resources.get(pRecipe.ResultId) != null;
                default:
                    return CustomItemRegistry.Has(pRecipe.ResultId);
            }
        }

        public static Sprite GetResultIcon(RecipeDefinition pRecipe)
        {
            switch (pRecipe.ResultKind)
            {
                case RecipeResultKind.Item:
                    EquipmentAsset asset = AssetManager.items.get(pRecipe.ResultId);
                    return asset != null ? asset.getSprite() : null;
                case RecipeResultKind.Resource:
                    ResourceAsset res = AssetManager.resources.get(pRecipe.ResultId);
                    return res != null ? res.getSpriteIcon() : null;
                default:
                    CustomItemDefinition def = CustomItemRegistry.Get(pRecipe.ResultId);
                    return def != null ? def.GetIcon() : null;
            }
        }

        public static string GetResultName(RecipeDefinition pRecipe)
        {
            switch (pRecipe.ResultKind)
            {
                case RecipeResultKind.Item:
                    EquipmentAsset asset = AssetManager.items.get(pRecipe.ResultId);
                    return asset != null ? asset.getTranslatedName() : pRecipe.ResultId;
                case RecipeResultKind.Resource:
                    ResourceAsset res = AssetManager.resources.get(pRecipe.ResultId);
                    return res != null ? res.getTranslatedName() : pRecipe.ResultId;
                default:
                    CustomItemDefinition def = CustomItemRegistry.Get(pRecipe.ResultId);
                    return def != null ? Loc.T(def.Name, def.Name) : pRecipe.ResultId;
            }
        }

        /// <summary>Checks ingredients, money, station and condition. <paramref name="pReason"/> explains a failure.</summary>
        public static bool CanCraft(Actor pActor, Inventory pInv, RecipeDefinition pRecipe, out string pReason)
        {
            pReason = null;
            if (pActor == null || pInv == null || pRecipe == null) return false;
            foreach (KeyValuePair<string, int> pair in pRecipe.Resources)
            {
                if (pActor.data.inventory.getResource(pair.Key) < pair.Value)
                {
                    ResourceAsset res = AssetManager.resources.get(pair.Key);
                    pReason = Loc.F("possesslib_craft_need", "Need $0", pair.Value + " " + (res != null ? res.getTranslatedName() : pair.Key));
                    return false;
                }
            }
            foreach (KeyValuePair<string, int> pair in pRecipe.CustomItems)
            {
                if (pInv.CountCustom(pair.Key) < pair.Value)
                {
                    CustomItemDefinition def = CustomItemRegistry.Get(pair.Key);
                    pReason = Loc.F("possesslib_craft_need", "Need $0", pair.Value + " " + (def != null ? Loc.T(def.Name, def.Name) : pair.Key));
                    return false;
                }
            }
            if (pRecipe.Money > 0 && pActor.data.money < pRecipe.Money)
            {
                pReason = Loc.F("possesslib_craft_need_money", "Need $0 coins", pRecipe.Money.ToString());
                return false;
            }
            if (pRecipe.NearBuildings != null && pRecipe.NearBuildings.Count > 0 && !IsNearStation(pActor, pRecipe))
            {
                pReason = Loc.F("possesslib_craft_need_station", "Must be near: $0", string.Join(", ", pRecipe.NearBuildings));
                return false;
            }
            if (pRecipe.Condition != null)
            {
                bool ok;
                try { ok = pRecipe.Condition(pActor); }
                catch (Exception e) { PLLog.Exception("Recipe condition " + pRecipe.Id, e); ok = false; }
                if (!ok)
                {
                    pReason = Loc.T("possesslib_craft_condition", "Requirements not met");
                    return false;
                }
            }
            if (pRecipe.ResultKind == RecipeResultKind.Item && pInv.FirstEmpty(true) < 0 && !PLConfig.EnableGroundItems)
            {
                pReason = Loc.T("possesslib_toast_inventory_full", "Inventory full");
                return false;
            }
            return true;
        }

        private static bool IsNearStation(Actor pActor, RecipeDefinition pRecipe)
        {
            WorldTile center = pActor.current_tile;
            if (center == null) return false;
            int radius = Mathf.Clamp(Mathf.CeilToInt(pRecipe.StationRadius), 1, 20);
            for (int dx = -radius; dx <= radius; dx++)
            {
                for (int dy = -radius; dy <= radius; dy++)
                {
                    WorldTile tile = World.world.GetTile(center.x + dx, center.y + dy);
                    Building b = tile != null ? tile.building : null;
                    if (b == null || b.asset == null) continue;
                    foreach (string wanted in pRecipe.NearBuildings)
                    {
                        if (string.IsNullOrEmpty(wanted)) continue;
                        bool match = wanted.EndsWith("*")
                            ? b.asset.id.StartsWith(wanted.Substring(0, wanted.Length - 1), StringComparison.Ordinal)
                            : b.asset.id == wanted;
                        if (match) return true;
                    }
                }
            }
            return false;
        }

        /// <summary>Crafts one result. Returns the produced stack, or null on failure (nothing is consumed then).</summary>
        public static ItemStack Craft(Actor pActor, Inventory pInv, RecipeDefinition pRecipe)
        {
            if (!CanCraft(pActor, pInv, pRecipe, out string reason))
            {
                if (reason != null) Toasts.Show(reason);
                UISound.Play(UISound.Deny);
                return null;
            }

            ItemStack produced;
            switch (pRecipe.ResultKind)
            {
                case RecipeResultKind.Item:
                {
                    EquipmentAsset asset = AssetManager.items.get(pRecipe.ResultId);
                    if (asset == null) return null;
                    int tries = Mathf.Max(1, pActor.asset.item_making_skill);
                    Item item = World.world.items.generateItem(asset, pActor.kingdom, pActor.getName(), tries, pActor, 0, false);
                    produced = ItemStack.FromItem(item);
                    if (!InventoryOps.AddItem(pActor, pInv, item))
                    {
                        GroundItems.Drop(produced, pActor.current_position, pActor);
                        Toasts.Show(Loc.T("possesslib_toast_full_ground", "Inventory full: it fell on the ground"));
                    }
                    break;
                }
                case RecipeResultKind.Resource:
                    produced = ItemStack.FromResource(pRecipe.ResultId, pRecipe.ResultCount);
                    InventoryOps.AddResource(pActor, pInv, pRecipe.ResultId, pRecipe.ResultCount);
                    break;
                default:
                {
                    produced = ItemStack.FromCustom(pRecipe.ResultId, pRecipe.ResultCount);
                    int left = InventoryOps.AddCustom(pInv, pRecipe.ResultId, pRecipe.ResultCount, null);
                    if (left > 0) GroundItems.Drop(ItemStack.FromCustom(pRecipe.ResultId, left), pActor.current_position, pActor);
                    break;
                }
            }

            foreach (KeyValuePair<string, int> pair in pRecipe.Resources) InventoryOps.RemoveResource(pActor, pInv, pair.Key, pair.Value);
            foreach (KeyValuePair<string, int> pair in pRecipe.CustomItems) pInv.RemoveAmount(StackKind.Custom, pair.Key, pair.Value);
            if (pRecipe.Money > 0) pActor.spendMoney(pRecipe.Money);

            UISound.Play(UISound.Craft);
            Toasts.Show(Loc.F("possesslib_toast_crafted", "Crafted $0", GetResultName(pRecipe)));
            PossessLibEvents.RaiseItemCrafted(pActor, pRecipe, produced);
            return produced;
        }
    }
}
